import sys
import zipfile
from collections import Counter
from pathlib import Path

import pytest

import androguard_rs
import fixture_apk as fx
from fixture_goldens import G
from resource_refs import resource_refs

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "compat"))
import androguard_compat as compat  # noqa: E402


def sig(ma):
    return f"{ma.class_name}->{ma.name}{ma.descriptor.replace(' ', '')}"


@pytest.fixture(scope="module")
def path(tmp_path_factory):
    return fx.build_apk(tmp_path_factory.mktemp("fx") / "fixture.apk")


@pytest.fixture(scope="module")
def dx(path):
    return compat.Analysis(androguard_rs.Apk(path))


def test_no_androguard_needed(path):
    """Importing and walking the facade doesn't import androguard (checked
    in a fresh process: other test modules here do import it)."""
    code = (f"import sys; sys.path[:0] = {[str(Path(compat.__file__).parent), str(Path(__file__).parent)]!r}\n"
            "import androguard_compat as c, androguard_rs\n"
            f"dx = c.Analysis(androguard_rs.Apk({path!r}))\n"
            "n = sum(len(ca.get_fields()) + len(ca.get_methods()) for ca in dx.get_classes())\n"
            "assert n and 'androguard' not in sys.modules, sorted(sys.modules)\n")
    out = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True)
    assert out.returncode == 0, out.stderr


def test_get_classes(dx, monkeypatch):
    assert [(c.name, c.is_external()) for c in dx.get_classes()] == G["classes"]
    assert len(dx.get_classes()) == len(G["classes"])
    # Smaller slices than the class count: the walk is still the same.
    monkeypatch.setattr(compat.Analysis, "_SLICE", 3)
    assert [c.name for c in dx.get_classes()] == [n for n, _ in G["classes"]]


def test_get_class_analysis(dx):
    for name, ext in G["classes"]:
        ca = dx.get_class_analysis(name)
        assert (ca.name, ca.is_external()) == (name, ext)
        assert dx.get_class_analysis(name) is ca  # interned while alive
    assert dx.get_class_analysis("Lno/such/Class;") is None
    assert dx.get_class_analysis("Lcom/ex/Main") is None
    assert dx.get_class_analysis(None) is None


def test_find_classes(dx):
    for pat, no_ext, exp in G["find_classes"]:
        assert [c.name for c in dx.find_classes(pat, no_ext)] == exp, pat


def test_get_class(dx):
    for name, sup, ifaces in G["hierarchy"]:
        cd = dx.get_class_analysis(name).get_class()
        assert (cd.get_name(), cd.get_superclassname(), cd.get_interfaces()) == (name, sup, ifaces)
    ext = dx.get_class_analysis("Lcom/ext/Lib;")
    assert isinstance(ext.get_class(), compat.ExternalClass) and ext.get_class().get_name() == "Lcom/ext/Lib;"
    assert ext.get_vm_class().get_name() == "Lcom/ext/Lib;"


def test_get_methods(dx):
    for name, _ in G["classes"]:
        rows = []
        for ma in dx.get_class_analysis(name).get_methods():
            em = ma.get_method()
            rows.append((sig(ma), em.get_name(), em.get_descriptor(), em.get_access_flags_string(), ma.is_external()))
            assert (ma.name, ma.class_name, em.get_class_name()) == (em.get_name(), name, name)
            assert ma.descriptor == em.get_descriptor()
            if ma.is_external():
                assert isinstance(em, compat.ExternalMethod) and em.name == ma.name
                with pytest.raises(AttributeError):
                    em.get_code()
            else:
                assert isinstance(em, compat.EncodedMethod) and em.name == ma.name
        assert rows == G["class_methods"][name], name


def test_instructions(dx):
    for name, _ in G["classes"]:
        for ma in dx.get_class_analysis(name).get_methods():
            if ma.is_external():
                continue
            em = ma.get_method()
            exp = G["bytecode"][sig(ma)]
            code = em.get_code()
            if exp is None:
                assert code is None and list(em.get_instructions_idx()) == []
                continue
            assert code
            assert [(o, i.get_name(), i.get_output()) for o, i in em.get_instructions_idx()] == exp
            assert [(i.get_name(), i.get_output()) for i in em.get_instructions()] == [e[1:] for e in exp]
            assert [(i.get_name(), i.get_output()) for i in code.get_bc().get_instructions()] == [e[1:] for e in exp]


def test_xrefs(dx):
    """Multisets: androguard's xrefs are sets."""
    def ends(xrefs):
        return sorted((sig(m), c.name, m.get_method().get_name(), m.get_method().get_descriptor(), off)
                      for c, m, off in xrefs)

    for name, _ in G["classes"]:
        for ma in dx.get_class_analysis(name).get_methods():
            assert ends(ma.get_xref_from()) == G["xref_from"][sig(ma)], sig(ma)
            assert ends(ma.get_xref_to()) == G["xref_to"][sig(ma)], sig(ma)
    # An xref endpoint fills in the rest of its row on demand.
    main_run = next(m for m in dx.get_class_analysis(fx.MAIN).get_methods() if m.name == "run")
    lib = next(m for _, m, _ in main_run.get_xref_to() if m.class_name == "Lcom/ext/Lib;")
    assert lib.is_external() and isinstance(lib.get_method(), compat.ExternalMethod)


def typed(v):
    if isinstance(v, list):
        return ("list", [typed(x) for x in v])
    if isinstance(v, compat._EncodedObject):
        return ("object", repr(v))
    return (type(v).__name__, v)


def test_get_fields(dx):
    for name, _ in G["classes"]:
        rows = []
        for fa in dx.get_class_analysis(name).get_fields():
            f = fa.get_field()
            assert fa.name == f.name == f.get_name()
            iv = f.init_value
            rows.append((f.get_class_name(), f.get_access_flags_string(), f.name, f.get_descriptor(),
                         None if iv is None else (repr(iv.value), typed(iv.value))))
        assert rows == G["class_fields"][name], name


def test_init_value_is_typed(dx):
    """init_value.value is a real int: it compares with ==, formats with
    :08x and reprs as a decimal."""
    for fa in dx.get_class_analysis(fx.R_STRING).get_fields():
        f = fa.get_field()
        if f.name == "app_name":
            v = f.init_value.value
            assert v == fx.APP_NAME_ID and f"{v:08x}" == "7f0b0001"
            assert repr(getattr(f.init_value, "value", f.init_value)) == "2131427329"
        if f.name == "z_no_value":
            assert getattr(f, "init_value", None) is None


def test_resource_refs(dx):
    """R field ids and the methods whose instruction literals use them."""
