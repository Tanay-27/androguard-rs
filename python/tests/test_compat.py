"""The androguard_compat facade on the synthetic APK (fixture_apk.py), with
no androguard installed: the Analysis object model (classes, methods,
fields, instructions, xrefs, the ARSCParser shim), against goldens from
androguard 4.1.3 (fixture_goldens.py, generated by
scripts/gen_fixture_goldens.py).

The facade ships in the wheel as androguard_rs._analysis; the tests import
its source from python/compat/ and build the Analysis directly from
androguard_rs.Apk.
"""

