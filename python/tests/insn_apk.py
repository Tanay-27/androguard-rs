"""A synthetic APK whose methods hold every instruction format androguard
4.1.3 decodes from DEX bytecode, for the Instruction API tests
(test_insn.py, against goldens from androguard 4.1.3 in insn_goldens.py,
generated by scripts/gen_insn_goldens.py).

classes.dex, class Lcom/ex/Ops;:
- allops: one instruction for every opcode androguard decodes (every byte
  but the unused ones), operands chosen to hit high nibbles, sign bits and
  all four reference kinds;
- variants: 35c with 0-7 registers, 3rc with 0, 1 and 255, 45cc with 0-5,
  4rcc, literal extremes of every const form, lit8/lit16 extremes;
- refs: out-of-range string/type/field/method indices, const-method-handle
  and const-method-type, invoke-custom, const-string/jumbo with an index of
  2**31 and more (androguard reads it as a signed int);
- payloads: packed-switch (with and without targets), sparse-switch with
  negative keys, fill-array-data of every element width, odd sizes padded;
- tail_fill / tail_packed: a payload whose length runs past the end of the
  method (fill data truncated, fewer packed targets read; the sweep ends
  there); tail_sparse: a payload as the last instruction;
- empty: no instructions at all; abstract: no code;
- bad_*: bytecode androguard rejects (unused opcode, nonzero padding, short
  read, unknown payload ident, 0x01ff, 45cc with 6 registers, payload header
  short, a nop whose high byte makes it a packed-switch too short to read).
"""

import io
import struct
import zipfile

import fixture_apk as fx

OPS = "Lcom/ex/Ops;"
OBJ = "Ljava/lang/Object;"
STR = "Ljava/lang/String;"

UNUSED = set(range(0x3E, 0x44)) | {0x73, 0x79, 0x7A} | set(range(0xE3, 0xFA))

# op -> format, as androguard 4.1.3's DALVIK_OPCODES_FORMAT
FMT = {}
for _ops, _f in [
    ([0x00, 0x0E], "10x"), ([0x01, 0x04, 0x07, 0x21, *range(0x7B, 0x90), *range(0xB0, 0xD0)], "12x"),
    ([0x02, 0x05, 0x08], "22x"), ([0x03, 0x06, 0x09], "32x"),
    ([*range(0x0A, 0x0E), 0x0F, 0x10, 0x11, 0x1D, 0x1E, 0x27], "11x"), ([0x12], "11n"), ([0x13, 0x16], "21s"),
    ([0x14, 0x17], "31i"), ([0x15, 0x19], "21h"), ([0x18], "51l"),
    ([0x1A, 0x1C, 0x1F, 0x22, *range(0x60, 0x6E), 0xFE, 0xFF], "21c"), ([0x1B], "31c"),
    ([0x20, 0x23, *range(0x52, 0x60)], "22c"), ([0x24, *range(0x6E, 0x73), 0xFC], "35c"),
    ([0x25, *range(0x74, 0x79), 0xFD], "3rc"), ([0x26, 0x2B, 0x2C], "31t"), ([0x28], "10t"), ([0x29], "20t"),
    ([0x2A], "30t"), ([*range(0x2D, 0x32), *range(0x44, 0x52), *range(0x90, 0xB0)], "23x"),
    (range(0x32, 0x38), "22t"), (range(0x38, 0x3E), "21t"), (range(0xD0, 0xD8), "22s"), (range(0xD8, 0xE3), "22b"),
    ([0xFA], "45cc"), ([0xFB], "4rcc"),
]:
    for _o in _ops:
        FMT[_o] = _f
assert set(FMT) | UNUSED == set(range(256))


def ref(c, op):
    """A valid reference index of the kind androguard gives `op`."""
    if op in (0x1A, 0x1B):
        return c.s("hello")
    if op in (0x1C, 0x1F, 0x20, 0x22, 0x23, 0x24, 0x25):
        return c.t("[I")
    if 0x52 <= op <= 0x6D:
        return c.f(OPS, "field", "I")
    if op in (0xFE,) or 0x6E <= op <= 0x78 or op in (0xFA, 0xFB):
        return c.m(OPS, "allops", "V")
    return 0  # proto / call site: androguard doesn't resolve them


def enc(op, c, **kw):
    """One instruction of opcode `op`, with distinctive default operands."""
    f, k = FMT[op], kw.get
    r = k("idx", None)
    if r is None and f in ("21c", "31c", "22c", "35c", "3rc", "45cc", "4rcc"):
        r = ref(c, op)
    if f == "10x":
        return bytes([op, 0])
    if f == "12x":
        return bytes([op, k("ab", 0xBA)])
    if f == "22x":
        return struct.pack("<BBH", op, 0xFE, 0xFFFE)
    if f == "32x":
        return struct.pack("<BBHH", op, 0, 0x1234, 0xFEDC)
    if f == "11x":
        return bytes([op, 0xFF])
    if f == "11n":
        return bytes([op, k("ab", 0x8F)])
    if f == "21s":
        return struct.pack("<BBh", op, 3, k("v", -32768))
    if f == "31i":
        return struct.pack("<BBi", op, 4, k("v", -2**31))
    if f == "21h":
        return struct.pack("<BBh", op, 5, k("v", -32767))
    if f == "51l":
        return struct.pack("<BBq", op, 6, k("v", -2**63 + 1))
    if f == "21c":
        # const-method-type's register must be v0: any other makes the unit
        # 0x..ff, which androguard reads as an unknown payload.
        return struct.pack("<BBH", op, 0 if op == 0xFF else 7, r)
    if f == "31c":
        return struct.pack("<BBI", op, 8, r)
    if f == "22c":
        return struct.pack("<BBH", op, 0x21, r)
    if f == "35c":
        a, g = k("a", 5), k("g", 9)
        return struct.pack("<BBHH", op, a << 4 | g, r, k("regs", 0x4321))
    if f == "3rc":
        return struct.pack("<BBHH", op, k("aa", 3), r, k("cccc", 10))
    if f == "31t":
        return struct.pack("<BBi", op, 9, k("v", -3))
    if f == "10t":
        return struct.pack("<Bb", op, k("v", -128))
    if f == "20t":
        return struct.pack("<BBh", op, 0, k("v", -32768))
    if f == "30t":
        return struct.pack("<BBi", op, 0, k("v", -2**31))
    if f == "23x":
        return bytes([op, 1, 2, 3])
    if f == "22t":
        return struct.pack("<BBh", op, 0x43, -16)
    if f == "21t":
        return struct.pack("<BBh", op, 2, 0x7FFF)
    if f == "22s":
        return struct.pack("<BBh", op, 0xBA, k("v", -32768))
    if f == "22b":
        return struct.pack("<BBBb", op, 1, 2, k("v", -128))
    if f == "45cc":
        return struct.pack("<BBHHH", op, k("a", 3) << 4 | k("g", 0), r, k("regs", 0x0321), k("h", 0))
    if f == "4rcc":
        return struct.pack("<BBHHH", op, k("aa", 2), r, 4, k("h", 0))
    raise AssertionError(f)


def packed(first_key, targets, size=None):
    return struct.pack("<HHi", 0x100, len(targets) if size is None else size, first_key) + b"".join(
        struct.pack("<i", t) for t in targets)


def sparse(pairs):
    return struct.pack("<HH", 0x200, len(pairs)) + b"".join(struct.pack("<i", k) for k, _ in pairs) + b"".join(
        struct.pack("<i", t) for _, t in pairs)


def fill(width, data, size=None):
    n = len(data) // width if size is None else size
    body = struct.pack("<HHI", 0x300, width, n) + data
    return body + (b"\0" if len(body) % 2 else b"")


def allops(c):
    return b"".join(enc(op, c) for op in range(256) if op not in UNUSED)


def variants(c):
    out = b""
    for a in range(8):
        out += enc(0x6E, c, a=a, g=a)
    out += enc(0x74, c, aa=0) + enc(0x74, c, aa=1) + enc(0x74, c, aa=255, cccc=0xFFFF)
    out += enc(0x24, c, a=1, g=0) + enc(0xFC, c, a=2, g=0) + enc(0xFD, c, aa=2)
    for a in range(6):
        out += enc(0xFA, c, a=a, g=0xF, regs=0xFEDC, h=7)
    out += enc(0xFB, c, aa=0) + enc(0xFB, c, aa=7, h=0xFFFF)
    for ab in (0x00, 0x70, 0x80, 0xF0, 0x1F):
        out += enc(0x12, c, ab=ab)
    for v in (-32768, -1, 0, 32767):
        out += enc(0x13, c, v=v) + enc(0x16, c, v=v) + enc(0x15, c, v=v) + enc(0x19, c, v=v) + enc(0xD0, c, v=v)
    for v in (-2**31, -1, 2**31 - 1):
        out += enc(0x14, c, v=v) + enc(0x17, c, v=v) + enc(0x2A, c, v=v) + enc(0x26, c, v=v)
    for v in (-2**63, -1, 2**63 - 1):
        out += enc(0x18, c, v=v)
    for v in (-128, -1, 127):
        out += enc(0xD8, c, v=v) + enc(0x28, c, v=v)
    out += enc(0x01, c, ab=0x00) + enc(0x01, c, ab=0xFF) + enc(0x29, c, v=1)
    return out


def refs(c):
    out = b""
    for op in (0x1A, 0x1C, 0x60, 0x52, 0x6E, 0x74, 0x24, 0xFE, 0xFF, 0xFC, 0xFD):
        out += enc(op, c, idx=0xFFFF) + enc(op, c, idx=1)
    for idx in (0, c.s("hello"), 0xFFFF, 0x10000, 0x7FFFFFFF, 0x80000000, 0xFFFFFFF0, 0xFFFFFFFF):
        out += enc(0x1B, c, idx=idx)
    out += enc(0x1A, c, idx=c.s("q'uo\"te\n\\é"))
    return out


def payloads(c):
    return (fx.RETURN_VOID + packed(-2, [10, -20, 30]) + packed(5, []) + sparse([(-5, 1), (0, -2), (2**31 - 1, 3)])
            + sparse([]) + fill(1, b"\x00\x7f\x80'\"") + fill(2, b"ab\xff\xfe") + fill(4, struct.pack("<i", -1))
            + fill(8, b"\x01" * 16) + fill(1, b"") + fill(3, b"abcdef"))


def tail_fill(c):
    return fx.RETURN_VOID + struct.pack("<HHI", 0x300, 1, 100) + b"xy"


def tail_packed(c):
    # size 100 overruns the 18 bytes left: androguard reads len(buff) - 16 = 2 targets.
    return struct.pack("<HHi", 0x100, 100, 7) + struct.pack("<ii", 1, 2) + b"\0\0"


def tail_sparse(c):
    return fx.RETURN_VOID + struct.pack("<HH", 0x200, 1) + struct.pack("<ii", 3, 4) + b""


def empty(c):
    return b""


BAD = {
    "bad_unused": lambda c: fx.RETURN_VOID + bytes([0x3E, 0]),
    "bad_padding": lambda c: bytes([0x0E, 0x01]),
    "bad_padding_32x": lambda c: fx.RETURN_VOID + struct.pack("<BBHH", 0x03, 1, 2, 3),
    "bad_nop_ident": lambda c: bytes([0x00, 0x01]),
    "bad_short": lambda c: fx.RETURN_VOID + bytes([0x14, 0]),
    "bad_ident": lambda c: bytes([0x00, 0x04]),
    "bad_ff": lambda c: bytes([0xFF, 0x01, 0, 0]),
    "bad_45cc": lambda c: enc(0xFA, c, a=6),
    "bad_payload_header": lambda c: fx.RETURN_VOID + bytes([0x00, 0x03, 0x01, 0x00]),
}


def classes():
    m = fx.meth
    direct = [m(n, flags=0x9, code=f, regs=16, ins=0, outs=5) for n, f in [
        ("allops", allops), ("variants", variants), ("refs", refs), ("payloads", payloads),
        ("tail_fill", tail_fill), ("tail_packed", tail_packed), ("tail_sparse", tail_sparse), ("empty", empty),
        *BAD.items()]]
    return [fx.cls(OPS, flags=0x401, static=[("field", "I", 0x9, None)], direct=direct,
                   virtual=[m("abstract", flags=0x401)])]


def dex() -> bytes:
    return fx.dex(classes())


def build_apk(path) -> str:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        z.writestr("classes.dex", dex())
    with open(path, "wb") as f:
        f.write(buf.getvalue())
    return str(path)
