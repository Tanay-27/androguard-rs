"""Generate core/src/axml_attrs.rs: androguard 4.1.3's system attribute table
(`public.SYSTEM_RESOURCES['attributes']['inverse']`, id -> name), which
`AXMLParser.getAttributeName()` uses to name attributes by resource id.

androguard builds it from its bundled AOSP `public.xml` (Apache-2.0); the
generated table is that data. Run with androguard 4.1.3 importable:

    python scripts/gen_axml_attrs.py > core/src/axml_attrs.rs
"""

from androguard.core.resources import public

inv = public.SYSTEM_RESOURCES["attributes"]["inverse"]
print("//! Generated by scripts/gen_axml_attrs.py from androguard 4.1.3's")
print("//! `public.SYSTEM_RESOURCES['attributes']['inverse']` (AOSP public.xml,")
print("//! Apache-2.0; see python/licenses/androguard-VENDORED.md). Do not edit.")
print()
print("/// (resource id, attribute name), sorted by id.")
print("pub(crate) static SYSTEM_ATTRS: &[(u32, &str)] = &[")
for k in sorted(inv):
    assert inv[k].isascii() and '"' not in inv[k] and "\\" not in inv[k]
    print(f'    (0x{k:08x}, "{inv[k]}"),')
print("];")
