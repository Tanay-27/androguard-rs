"""Write python/tests/arsc_config_goldens.py: androguard 4.1.3's
get_resolved_res_configs() on arsc_config_cases.tables(), every config
object as its type name, vars(), repr(), hash() and method values.

    python scripts/gen_arsc_config_goldens.py   # in a venv with androguard 4.1.3
"""
import pprint
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "python" / "tests"))

from loguru import logger  # noqa: E402

logger.remove()
from androguard.core.axml import ARSCParser  # noqa: E402

import arsc_config_cases as C  # noqa: E402
from arsc_config_view import tree_view  # noqa: E402

out = {}
for name, raw in C.tables().items():
    p = ARSCParser(raw)
    out[name] = [(rid, tree_view(p.get_resolved_res_configs(rid))) for rid in C.RIDS]
dst = ROOT / "python" / "tests" / "arsc_config_goldens.py"
dst.write_text('"""Generated by scripts/gen_arsc_config_goldens.py from androguard 4.1.3."""\n\nGOLDENS = '
               + pprint.pformat(out, width=120) + "\n")
print("wrote", dst)
