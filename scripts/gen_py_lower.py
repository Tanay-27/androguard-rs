"""Generate core/src/py_lower_tables.rs: the tables CPython's str.lower()
uses, taken from this Python, so Rust reproduces lower() exactly for this
Python's Unicode version (Rust's own tables are newer and differ).
Regenerate with the Python minor version androguard runs under.

  LOWER         code point -> its full lowercase mapping (if not itself)
  IGNORABLE     Case_Ignorable ranges
  CASED         Cased ranges (only consulted for non-ignorable chars)

The two properties drive the final-sigma rule and aren't exposed by Python,
so they're derived by probing lower() itself:
  (c + "Σ").lower() ends in "ς"   <=>  c is cased and not ignorable
  ("A" + c + "Σ").lower() ends in "ς"  <=>  c is ignorable or cased

usage: python gen_py_lower.py > core/src/py_lower_tables.rs
"""

import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(sys.maxunicode + 2):
        p = cp <= sys.maxunicode and not 0xD800 <= cp <= 0xDFFF and pred(cp)
        if p and start is None:
            start = cp
        elif not p and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def ends_final(s):
    return s.lower()[-1] == "ς"


def cased_not_ignorable(cp):
    return ends_final(chr(cp) + "Σ")


def ignorable(cp):
    return ends_final("A" + chr(cp) + "Σ") and not cased_not_ignorable(cp)


lower = [(cp, chr(cp).lower()) for cp in range(sys.maxunicode + 1)
         if not 0xD800 <= cp <= 0xDFFF and chr(cp).lower() != chr(cp)]

v = sys.version_info
print(f"// @generated by scripts/gen_py_lower.py with Python {v.major}.{v.minor}.{v.micro} "
      f"(Unicode {unicodedata.unidata_version}). Do not edit.")
print("//! CPython str.lower() tables; see render::py_lower.\n")
print(f"pub const LOWER: [(u32, &str); {len(lower)}] = [")
for cp, s in lower:
    lit = "".join(f"\\u{{{ord(c):x}}}" for c in s)
    print(f'    (0x{cp:X}, "{lit}"),')
print("];\n")
for name, pred in [("IGNORABLE", ignorable), ("CASED", cased_not_ignorable)]:
    rs = ranges(pred)
    print(f"pub const {name}: [(u32, u32); {len(rs)}] = [")
    for a, b in rs:
        print(f"    (0x{a:X}, 0x{b:X}),")
    print("];\n")
