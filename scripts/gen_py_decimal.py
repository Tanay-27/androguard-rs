"""Generate core/src/py_decimal.rs: the code-point ranges Python's `re`
matches with `\\d` in a str pattern (Unicode decimal digits), so Rust can
apply androguard's `^classes(\\d*).dex$` DEX-name filter exactly.
Regenerate with the Python minor version androguard runs under.

usage: python gen_py_decimal.py > core/src/py_decimal.rs
"""

import re
import sys
import unicodedata

digit = re.compile(r"\d")
ranges = []
start = None
for cp in range(0x80, 0x110000):
    p = digit.match(chr(cp)) is not None
    if p and start is None:
        start = cp
    elif not p and start is not None:
        ranges.append((start, cp - 1))
        start = None
if start is not None:
    ranges.append((start, 0x10FFFF))

v = sys.version_info
print(f"// @generated by scripts/gen_py_decimal.py with Python {v.major}.{v.minor}.{v.micro} "
      f"(Unicode {unicodedata.unidata_version}). Do not edit.")
print("//! Non-ASCII code-point ranges Python's `re` matches with `\\d` (str patterns).\n")
print(f"pub const DECIMAL: [(u32, u32); {len(ranges)}] = [")
for a, b in ranges:
    print(f"    (0x{a:X}, 0x{b:X}),")
print("];")
