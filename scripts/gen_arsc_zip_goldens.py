"""Regenerate python/tests/arsc_zip_goldens.py: what androguard 4.1.3's
APK.get_android_resources() reads from python/tests/arsc_zip_cases.py's
tampered zips, for test_arsc_zip.py, which then runs without androguard.

    python scripts/gen_arsc_zip_goldens.py      # in a venv with androguard 4.1.3
"""

import logging
import pprint
import sys
from pathlib import Path

from loguru import logger

logger.disable("androguard")
logging.disable(logging.WARNING)  # apkInspector's "Does not seem to be the start of a local header!"

HERE = Path(__file__).resolve().parent
TESTS = HERE.parent / "python" / "tests"
sys.path.insert(0, str(TESTS))

from androguard.core.apk import APK  # noqa: E402

import arsc_zip_cases as Z  # noqa: E402


def androguard_view(raw):
    a = APK(raw, raw=True)
    res = a.get_android_resources()
    return Z.view(res, None if res is None else a.get_file("resources.arsc"))


def main():
    golden = {name: Z.outcome(lambda: androguard_view(mk())) for name, mk in Z.CASES.items()}
    out = TESTS / "arsc_zip_goldens.py"
    with open(out, "w") as f:
        f.write('"""Generated by scripts/gen_arsc_zip_goldens.py from androguard 4.1.3 on\n'
                'arsc_zip_cases.py\'s APKs. Do not edit."""\n\n')
        f.write("GOLDEN = " + pprint.pformat(golden, width=120, sort_dicts=False) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
