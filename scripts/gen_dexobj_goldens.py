"""Regenerate the goldens of the strict-load, by-index/by-signature and
per-DEX object-model tests from androguard 4.1.3 (with mutf8 1.1.0):

- python/tests/strict_goldens.py  (strict_cases.py: what AnalyzeAPK and a
  manual DEX()/Analysis.add() load raise or load)
- python/tests/sig_goldens.py     (sig_cases.py: string xrefs through
  signed const-string/jumbo indices, "->" in class names)
- python/tests/dexobj_goldens.py  (dexobj_cases.py: the object-model views,
  from AnalyzeAPK and from the manual load)

test_strict.py, test_sig.py and test_dexobj.py then run without
androguard.

    python scripts/gen_dexobj_goldens.py      # in a venv with androguard 4.1.3
"""

import logging
import pprint
import sys
from pathlib import Path

from loguru import logger

logger.disable("androguard")
logging.disable(logging.WARNING)

HERE = Path(__file__).resolve().parent
TESTS = HERE.parent / "python" / "tests"
sys.path.insert(0, str(TESTS))

from androguard.core.analysis.analysis import Analysis  # noqa: E402
from androguard.core.apk import APK  # noqa: E402
from androguard.core.dex import DEX  # noqa: E402
from androguard.misc import AnalyzeAPK  # noqa: E402

import dexobj_cases as SH  # noqa: E402
import sig_cases as SG  # noqa: E402
import strict_cases as ST  # noqa: E402


def manual(raw):
    """APK.get_all_dex() -> DEX() -> Analysis.add() -> create_xref(): (vms, vmx)."""
    a = APK(raw, raw=True)
    vmx = Analysis()
    vms = []
    for b in a.get_all_dex():
        v = DEX(b)
        vmx.add(v)
        vms.append(v)
        v.set_analysis(vmx)
    vmx.create_xref()
    return vms, vmx


def write(name, var, value, what):
    out = TESTS / name
    with open(out, "w") as f:
        f.write(f'"""Generated by scripts/gen_dexobj_goldens.py from androguard 4.1.3 (mutf8 1.1.0)\n'
                f'on {what}. Do not edit."""\n\n')
        f.write(f"{var} = " + pprint.pformat(value, width=120, sort_dicts=False) + "\n")
    print(f"wrote {out}")


def main():
    strict = {name: {"analyze": ST.analyze(AnalyzeAPK, mk()), "manual": ST.manual(APK, DEX, Analysis, mk())}
              for name, mk in ST.CASES.items()}
    write("strict_goldens.py", "GOLDEN", strict, "strict_cases.py's APKs")

    sig = {"strings": SG.ag_strings(AnalyzeAPK(SG.strings_apk(), raw=True)[2]),
           "arrow": SG.ag_arrow(AnalyzeAPK(SG.arrow_apk(), raw=True)[2])}
    write("sig_goldens.py", "GOLDEN", sig, "sig_cases.py's APKs")

    raw = SH.apk()
    _, d, dx = AnalyzeAPK(raw, raw=True)
    views = SH.views(d, dx)
    assert SH.views(*manual(raw)) == views
    write("dexobj_goldens.py", "GOLDEN", views, "dexobj_cases.apk()")


if __name__ == "__main__":
    main()
