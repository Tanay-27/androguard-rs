"""Regenerate python/tests/insn_goldens.py: what androguard 4.1.3 (with mutf8
1.1.0) shows of every instruction of python/tests/insn_apk.py's methods
(insn_shapes.method_shape), for test_insn.py, which then runs without
androguard.

    python scripts/gen_insn_goldens.py      # in a venv with androguard 4.1.3

androguard's DEX() is used directly: AnalyzeAPK would fail on the bad_*
methods. method_shape() iterates each method first, which leaves
androguard's per-method instruction cache filled, as create_xref() does.
"""

import sys
from pathlib import Path

from loguru import logger

logger.disable("androguard")

HERE = Path(__file__).resolve().parent
TESTS = HERE.parent / "python" / "tests"
sys.path.insert(0, str(TESTS))

from androguard.core.dex import DEX  # noqa: E402

import insn_apk  # noqa: E402
from insn_shapes import flatten, method_shape  # noqa: E402


def main():
    d = DEX(insn_apk.dex())
    goldens, table = {}, {}
    for c in d.get_classes():
        for m in c.get_methods():
            shape = method_shape(m)
            if "insns" in shape:
                # Each part of an instruction's shape is stored once in T;
                # instructions are lists of indices into it (insn_shapes.expand).
                shape["insns"] = [[table.setdefault(part, len(table)) for part in flatten(i)] for i in shape["insns"]]
            goldens[f"{c.get_name()}->{m.get_name()}{m.get_descriptor()}"] = shape
    out = TESTS / "insn_goldens.py"
    out.write_text(
        '"""Generated by scripts/gen_insn_goldens.py from androguard 4.1.3 (mutf8 1.1.0) on\n'
        'insn_apk.py\'s DEX. Do not edit. Instructions are lists of indices into T\n'
        '(insn_shapes.expand() turns them back into insn_shape() tuples)."""\n\n'
        "# fmt: off\n"
        "T = [\n" + "".join(f"    {part!r},\n" for part in table) + "]\n\n"
        "G = {\n" + "".join(f"    {k!r}: {goldens[k]!r},\n" for k in sorted(goldens)) + "}\n")
    print(f"wrote {out}: {len(goldens)} methods, {sum(len(g.get('insns', [])) for g in goldens.values())} instructions")


if __name__ == "__main__":
    main()
