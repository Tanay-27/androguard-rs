"""Generate spike/src/py_printable.rs: the code-point ranges for which this
Python's str.isprintable() is true, so Rust can reproduce repr(str) exactly.
Regenerate with the Python minor version androguard runs under.

usage: python gen_py_printable.py > spike/src/py_printable.rs
"""

import sys
import unicodedata

ranges = []
start = None
for cp in range(0x80, 0x110000):
    p = chr(cp).isprintable()
    if p and start is None:
        start = cp
    elif not p and start is not None:
        ranges.append((start, cp - 1))
        start = None
if start is not None:
    ranges.append((start, 0x10FFFF))

v = sys.version_info
print(f"// @generated by scripts/gen_py_printable.py with Python {v.major}.{v.minor}.{v.micro} "
      f"(Unicode {unicodedata.unidata_version}). Do not edit.")
print("//! Non-ASCII code-point ranges for which Python's str.isprintable() is true.\n")
print(f"pub const PRINTABLE: [(u32, u32); {len(ranges)}] = [")
for a, b in ranges:
    print(f"    (0x{a:X}, 0x{b:X}),")
print("];")
