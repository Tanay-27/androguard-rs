"""Regenerate python/tests/dup_goldens.py: what androguard 4.1.3 (with mutf8
1.1.0) answers on python/tests/dup_cases.py's APKs with classes defined more
than once, for test_dup_classes.py, which then runs without androguard.

    python scripts/gen_dup_goldens.py      # in a venv with androguard 4.1.3
"""

import logging
import pprint
import sys
from pathlib import Path

from loguru import logger

logger.disable("androguard")
logging.disable(logging.WARNING)

HERE = Path(__file__).resolve().parent
TESTS = HERE.parent / "python" / "tests"
sys.path.insert(0, str(TESTS))

from androguard.misc import AnalyzeAPK  # noqa: E402

import dup_cases as K  # noqa: E402


def main():
    golden = {name: K.ag_views(AnalyzeAPK(mk(), raw=True)[2]) for name, mk in K.CASES.items()}
    out = TESTS / "dup_goldens.py"
    with open(out, "w") as f:
        f.write('"""Generated by scripts/gen_dup_goldens.py from androguard 4.1.3 (mutf8 1.1.0)\n'
                'on dup_cases.py\'s APKs. Do not edit."""\n\n')
        f.write("GOLDEN = " + pprint.pformat(golden, width=120, sort_dicts=False) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
