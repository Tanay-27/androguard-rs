"""Regenerate python/tests/dex_order_goldens.py: what androguard 4.1.3 (with
mutf8 1.1.0) answers on python/tests/dex_order_cases.py's synthetic APKs, for
test_dex_order.py, which then runs without androguard.

    python scripts/gen_dex_order_goldens.py      # in a venv with androguard 4.1.3
"""

import logging
import pprint
import sys
from pathlib import Path

from loguru import logger

logger.disable("androguard")
logging.disable(logging.WARNING)  # apkInspector's "Does not seem to be the start of a local header!"

HERE = Path(__file__).resolve().parent
TESTS = HERE.parent / "python" / "tests"
sys.path.insert(0, str(TESTS))

from androguard.core.analysis.analysis import Analysis  # noqa: E402
from androguard.core.dex import DEX  # noqa: E402
from androguard.misc import AnalyzeAPK  # noqa: E402

import dex_order_cases as C  # noqa: E402


def main():
    golden, extras = {}, {}
    for name, mk in C.CASES.items():
        raw = mk()
        golden[name] = C.outcome(lambda: C.snapshot(*AnalyzeAPK(raw, raw=True)))
        if isinstance(golden[name], dict) and ("LA;", False) in golden[name]["classes"] and golden[name]["n_dex"] > 1:
            extras[name] = C.duplicate_extras(AnalyzeAPK(raw, raw=True)[2])
    tolerant = {name: C.outcome(lambda: C.tolerant_load(mk(), DEX, Analysis)) for name, mk in C.CASES.items()}
    out = TESTS / "dex_order_goldens.py"
    with open(out, "w") as f:
        f.write('"""Generated by scripts/gen_dex_order_goldens.py from androguard 4.1.3 (mutf8 1.1.0)\n'
                'on dex_order_cases.py\'s APKs. Do not edit."""\n\n')
        f.write("GOLDEN = " + pprint.pformat(golden, width=120, sort_dicts=False) + "\n\n")
        f.write("TOLERANT = " + pprint.pformat(tolerant, width=120, sort_dicts=False) + "\n\n")
        f.write("DUPLICATE_EXTRAS = " + pprint.pformat(extras, width=120, sort_dicts=False) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
